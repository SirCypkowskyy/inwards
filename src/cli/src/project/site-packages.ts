/**
 * @file Finds the site-packages directories of a project's virtualenv, so
 * INW010 sees the portions of a namespace package that installed
 * distributions provide (#161). It looks only for a `.venv` directory in the
 * places uv and `python -m venv` put one, reads through the injected
 * `ProjectIo`, and runs no Python: the interpreter's own paths (`.pth` files,
 * editable installs, `VIRTUAL_ENV`) are left out, so every run of the same
 * checkout sees the same directories.
 */
import { join } from "node:path";
import type { ProjectIo } from "./contracts.ts";

/** A virtualenv's `lib/` entry for an interpreter: `python3.13`, `pypy3.10`. */
const INTERPRETER = /^(?:python|pypy)\d/u;

/**
 * Lists the site-packages directories of the `.venv` in each directory:
 * `lib/python3.x/site-packages` on POSIX, `Lib/site-packages` on Windows.
 * A directory that can't be listed gives nothing rather than failing the
 * check, since the answer only spares findings.
 *
 * @param io - lists directories and tells what a path is.
 * @param dirs - absolute directories that may hold a `.venv`, such as the
 *   config's directory and the uv workspace root.
 * @returns the existing site-packages directories, in the order found.
 */
export function sitePackages(
  io: Pick<ProjectIo, "probe" | "read">,
  dirs: readonly string[],
): string[] {
  return dirs.flatMap((dir) => {
    const venv = join(dir, ".venv");
    let versions: string[] = [];
    try {
      versions = (io.read.list(join(venv, "lib")) ?? [])
        .filter((entry) => entry.dir && INTERPRETER.test(entry.name))
        .map((entry) => join(venv, "lib", entry.name, "site-packages"));
    } catch {
      // Unreadable: no portions from this virtualenv.
    }
    return [...versions, join(venv, "Lib", "site-packages")].filter(
      (path) => io.probe.kind(path) === "dir",
    );
  });
}
